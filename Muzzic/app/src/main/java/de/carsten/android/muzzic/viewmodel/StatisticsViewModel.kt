package de.carsten.android.muzzic.viewmodel

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import de.carsten.android.muzzic.persistence.entity.aggregation.GenrePlayCount
import de.carsten.android.muzzic.persistence.repo.AlbumRepository
import de.carsten.android.muzzic.persistence.repo.ArtistRepository
import de.carsten.android.muzzic.persistence.repo.GenreRepository
import de.carsten.android.muzzic.persistence.repo.MusicRepository
import de.carsten.android.muzzic.persistence.repo.PlaylistRepository
import de.carsten.android.muzzic.ui.state.StatisticsUiState
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Deferred
import kotlinx.coroutines.async
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch

class StatisticsViewModel(
    private val repository: MusicRepository,
    private val genreRepository: GenreRepository,
    private val playlistRepository: PlaylistRepository,
    private val artistRepository: ArtistRepository,
    private val albumRepository: AlbumRepository,
) : ViewModel(),
    UiStateViewModel<StatisticsUiState> {
    private val _uiState = MutableStateFlow(StatisticsUiState())
    override val uiState: StateFlow<StatisticsUiState> = _uiState.asStateFlow()

    /**
     * Loads all statistics concurrently and publishes them progressively.
     *
     * The overall, current-month and library groups run in parallel (total
     * latency is the slowest group, not the sum), share a single genre-variant
     * count query, and each group updates the UI state as soon as it arrives —
     * so the first tab renders before the heavy library aggregations finish.
     */
    fun loadStats() {
        viewModelScope.launch {
            val genreCounts = async { genreRepository.getGenreCounts() }
            val overall = async { loadOverallTab(genreCounts) }
            val month = async { loadMonthTab(genreCounts) }
            val library = async { loadLibraryTab() }
            overall.await()
            month.await()
            library.await()
        }
    }

    /**
     * Loads only the statistics group for the given tab index.
     *
     * Each tab owns disjoint state fields, so switching tabs never clobbers
     * already loaded data. Queries within the group run in parallel.
     *
     * @param index tab index: 0 overall, 1 current month, 2 library.
     */
    fun loadTab(index: Int) {
        viewModelScope.launch {
            when (index) {
                TAB_OVERALL -> {
                    val genreCounts = async { genreRepository.getGenreCounts() }
                    loadOverallTab(genreCounts)
                }

                TAB_MONTH -> {
                    val genreCounts = async { genreRepository.getGenreCounts() }
                    loadMonthTab(genreCounts)
                }

                TAB_LIBRARY -> loadLibraryTab()

                else -> Unit
            }
        }
    }

    private suspend fun CoroutineScope.loadOverallTab(genreCounts: Deferred<List<GenrePlayCount>>) {
        val monthlyStats = async { repository.getMonthlyStats() }
        val genreStats = async { repository.getGenreStats(genreCounts.await()) }
        val topSongs = async { repository.getTopSongs() }
        _uiState.update {
            it.copy(
                monthlyStats = monthlyStats.await(),
                genreStats = genreStats.await(),
                topSongs = topSongs.await(),
            )
        }
    }

    private suspend fun CoroutineScope.loadMonthTab(genreCounts: Deferred<List<GenrePlayCount>>) {
        val monthStats = async { repository.getMonthStats() }
        val monthGenreStats = async { repository.getMonthGenreStats(genreCounts.await()) }
        val topMonthSongs = async { repository.getTopMonthSongs() }
        _uiState.update {
            it.copy(
                monthStats = monthStats.await(),
                monthGenreStats = monthGenreStats.await(),
                topMonthSongs = topMonthSongs.await(),
            )
        }
    }

    private suspend fun CoroutineScope.loadLibraryTab() {
        val librarySummary = async { repository.getLibrarySummary() }
        val genreDurations = async { genreRepository.getGenreInformation().first() }
        val playlistDurations = async { playlistRepository.getPlaylistInformation().first() }
        val recentArtists = async { artistRepository.getRecentArtists() }
        val recentAlbums = async { albumRepository.getRecentAlbums() }
        _uiState.update {
            it.copy(
                librarySummary = librarySummary.await(),
                genreDurations = genreDurations.await(),
                playlistDurations = playlistDurations.await().filter { !it.playlistIsAutoGenerated },
                recentArtists = recentArtists.await(),
                recentAlbums = recentAlbums.await(),
            )
        }
    }

    companion object {
        const val TAB_OVERALL = 0
        const val TAB_MONTH = 1
        const val TAB_LIBRARY = 2
    }
}
