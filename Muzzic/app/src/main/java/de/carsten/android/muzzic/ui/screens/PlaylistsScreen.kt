@Composable
fun PlaylistsScreen(
    modifier: Modifier = Modifier,
    appState: MusicAppState,
    libraryViewModel: LibraryViewModel = koinViewModel(),
    playingQueueViewModel: PlayingQueueViewModel,
    onPlaylistClick: (PlaylistDto) -> Unit = {},
    onPlayPlaylist: (PlaylistDto) -> Unit = {},
    onDeletePlaylist: (PlaylistDto) -> Unit = {},
) {
    val playlists by libraryViewModel.playlists.collectAsStateWithLifecycle()
    AppTheme {
        PlaylistScreenContent(
            modifier = modifier,
            playlists = playlists,
            onPlaylistClick = onPlaylistClick,
            onPlayClick = onPlayPlaylist,
            onDeleteClick = onDeletePlaylist,
        )
    }
}

@Composable
fun PlaylistScreenContent(
    modifier: Modifier,
    playlists: List<PlaylistDto>,
    onPlaylistClick: (PlaylistDto) -> Unit = {},
    onPlayClick: (PlaylistDto) -> Unit = {},
    onDeleteClick: (PlaylistDto) -> Unit = {},
) {
    Column(
        modifier =
        modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background),
    ) {
        // Header
        Row(
            modifier =
            Modifier
                .fillMaxWidth()
                .padding(16.dp),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Text(
                text = stringResource(R.string.playlists),
                color = MaterialTheme.colorScheme.onBackground,
                fontSize = 24.sp,
                fontWeight = FontWeight.Bold,
            )

            IconButton(onClick = { /* Add playlist */ }) {
                Icon(
                    Icons.Default.Add,
                    contentDescription = stringResource(R.string.add_playlists),
                    tint = MaterialTheme.colorScheme.onBackground,
                )
            }
        }

        LazyColumn(
            modifier =
            Modifier
                .padding(horizontal = 16.dp)
                .fillMaxWidth(),
            verticalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            item {
                Text(
                    text = stringResource(R.string.auto_playlists),
                    color = MaterialTheme.colorScheme.onBackground,
                    fontSize = 16.sp,
                    fontWeight = FontWeight.SemiBold,
                    modifier = Modifier.padding(vertical = 8.dp),
                )
            }

            item {
                val autoPlaylists =
                    remember(playlists) {
                        playlists.filter { it.playlistIsAutoGenerated }
                    }
                Column {
                    autoPlaylists.forEach { playlist ->
                        PlaylistListItem(
                            playlist = playlist,
                            iconColor = MaterialTheme.colorScheme.onBackground,
                            modifier = Modifier.padding(vertical = 4.dp),
                            showGenre = playlist.playlistIsAutoGenerated,
                            onPlaylistClick = { onPlaylistClick(playlist) },
                            onPlayClick = { onPlayClick(playlist) },
                            onDeleteClick = { onDeleteClick(playlist) },
                        )
                    }
                }
            }

            item {
                Text(
                    text = "Meine Playlists",
                    color = MaterialTheme.colorScheme.onBackground,
                    fontSize = 16.sp,
                    fontWeight = FontWeight.SemiBold,
                    modifier = Modifier.padding(vertical = 8.dp),
                )
            }

            item {
                val userPlaylists =
                    remember(playlists) {
                        playlists.filter { !it.playlistIsAutoGenerated }
                    }
                Column {
                    userPlaylists.forEach { playlist ->
                        PlaylistListItem(
                            playlist = playlist,
                            iconColor = MaterialTheme.colorScheme.onBackground,
                            modifier = Modifier.padding(vertical = 4.dp),
                            onPlaylistClick = { onPlaylistClick(playlist) },
                            onPlayClick = { onPlayClick(playlist) },
                            onDeleteClick = { onDeleteClick(playlist) },
                        )
                    }
                }
            }
        }
    }
}

