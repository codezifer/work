package de.carsten.android.muzzic.persistence.entity

import android.os.Bundle
import androidx.media3.common.MediaItem
import androidx.media3.common.MediaMetadata
import androidx.room.Entity
import de.carsten.android.muzzic.UNKNOWN
import de.carsten.android.muzzic.model.MediaKeys

@Entity(tableName = Playlist.TABLE_NAME)
data class Playlist(val name: String, val isAutoGenerated: Boolean = false, val genre: String? = null) : AbstractEntity() {
    companion object {
        const val TABLE_NAME = "playlists"
    }

    fun toMediaItem(): MediaItem = MediaItem
        .Builder()
        .setMediaId("${MediaKeys.PLAYLIST_PREFIX}$name")
        .setMediaMetadata(
            MediaMetadata
                .Builder()
                .setTitle(name)
                .setExtras(
                    Bundle().apply {
                        putBoolean(MediaKeys.IS_AUTO_GENERATED, isAutoGenerated)
                        putString(MediaKeys.GENRE, genre ?: UNKNOWN)
                    },
                ).setIsBrowsable(true)
                .setIsPlayable(false)
                .build(),
        ).build()
}
